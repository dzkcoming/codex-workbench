// Records an isolated real Tabby window; all log data is synthetic.
import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import assert from 'node:assert/strict';
import { launchTabby, openProfile, selectText, visibleText, until, delay } from './tabby-harness.mjs';
const exec = promisify(execFile);
const dir=mkdtempSync(resolve('test-results/demo-'));
const workspace=mkdtempSync(join(tmpdir(),'codex-workbench-demo-'));
mkdirSync(join(workspace,'firmware'));
const shell={type:'local',name:'Demo Shell',options:{command:'/bin/bash',args:['--noprofile','--norc'],cwd:workspace,env:{PS1:'demo \\w $ '}}};
let instance,recording=false,loop;
const frames=[],chapters=[]; let start;
const stamp=ms=>{const s=Math.floor(ms/1000);return `${String(Math.floor(s/3600)).padStart(2,'0')}:${String(Math.floor(s/60)%60).padStart(2,'0')}:${String(s%60).padStart(2,'0')},${String(Math.floor(ms%1000)).padStart(3,'0')}`};
async function chapter(text){chapters.push({time:Date.now()-start,text});console.log(text);await delay(900);}
try {
 instance=await launchTabby(join(dir,'app'),workspace);const {page}=instance;
 await page.evaluate(()=>{const w=require('@electron/remote').getCurrentWindow();w.unmaximize();w.setSize(1440,900);__test.layout=__test.injector.get(__test.plugin.PaneLayoutService);__test.direct=__test.injector.get(__test.plugin.CodexReferenceService);});
 await openProfile(page,'Codex',shell);
 await page.keyboard.type('codex --sandbox workspace-write --ask-for-approval on-request');await page.keyboard.press('Enter');
 await until(async()=>{const t=await visibleText(page,'Codex');return t.includes('Ask Codex to do anything')&&/for agents|for shortcuts/.test(t)&&!t.includes('loading');},45000);
 await page.keyboard.type('Help me investigate this demo USB timeout.');
 const handle=await page.evaluate(()=>require('@electron/remote').getCurrentWindow().getNativeWindowHandle().readUInt32LE(0));
 start=Date.now();recording=true;
 loop=(async()=>{while(recording){const file=join(dir,`frame-${String(frames.length).padStart(5,'0')}.png`);const time=Date.now();await exec('import',['-window',String(handle),file]);frames.push({file,time});await delay(160);}})();
 await chapter('Codex Workbench  |  原版 Codex + Tabby · 独立窗口实录');await delay(3000);
 await chapter('01  分屏：同一顶部标签内，左侧 Codex，右侧调试终端');
 await page.evaluate(async()=>{const s=__test;s.root=s.tabs.Codex.topmostParent;s.left=s.layout.enable(s.root);s.right=await s.layout.split(s.left,'r');});
 await page.waitForFunction(()=>__test.right.active?.session?.open);
 await page.evaluate(()=>{__test.tabs.logs=__test.right.active;__test.tabs.logs.setCustomTitle('UART · 演示日志');});
 await page.waitForFunction(()=>__test.tabs.logs.frontendIsReady&&__test.tabs.logs.session?.open);
 await page.keyboard.type("printf '\\033[2J\\033[H[DEMO UART] USB initialization\\nUSB init: OK\\ntransfer timeout: endpoint=1, retries=3\\nDMA state: idle\\n'");await page.keyboard.press('Enter');await delay(2500);
 await chapter('02  选中右侧日志 → Ctrl+Shift+Y → 左侧 Codex 草稿');
 await selectText(page,'logs','transfer timeout: endpoint=1, retries=3');await delay(1800);
 await page.waitForFunction(()=>__test.direct.ready(__test.tabs.Codex));
 await page.keyboard.press('Control+Shift+Y');
 await until(async()=>(await visibleText(page,'Codex')).includes('transfer timeout'));
 assert.match(await visibleText(page,'Codex'),/Help me investigate/);await delay(4200);
 await chapter('保留已有草稿，不自动提交；可继续选取其他终端输出');await delay(3000);
 await chapter('03  Ctrl+Shift+T：在当前分屏新增标签，并继承工作目录');
 await page.evaluate(()=>{__test.right.select(__test.tabs.logs);__test.tabs.logs.frontend.clearSelection();});
 await page.keyboard.type('cd firmware');await page.keyboard.press('Enter');await delay(500);
 await page.keyboard.press('Control+Shift+T');
 await page.waitForFunction(()=>__test.right.tabs.length===2&&__test.right.active.session?.open);
 await page.keyboard.type('pwd');await page.keyboard.press('Enter');await delay(2300);
 await chapter('04  双击标签改名，Alt+1 / Alt+2 切换分屏内部标签');
 const tabs=page.locator('workbench-pane-tabs').nth(1).getByRole('tab');
 await tabs.nth(1).dblclick();const input=page.locator('rename-tab-modal input');await input.waitFor();await input.fill('GDB · 演示日志');await delay(1400);await input.press('Enter');await input.waitFor({state:'detached'});
 await page.keyboard.type("printf '[DEMO GDB] breakpoint at usb_transfer\\nstatus = TIMEOUT\\n'");await page.keyboard.press('Enter');await delay(1700);
 await page.keyboard.press('Alt+1');await delay(1800);await page.keyboard.press('Alt+2');await delay(1800);
 await chapter('05  Alt+方向键：在分屏之间移动焦点');
 await page.keyboard.press('Alt+ArrowLeft');await delay(1800);await page.keyboard.press('Alt+ArrowRight');await delay(1800);
 await chapter('06  网页 / 本地 HTML：与终端共用分屏内部标签');
 const html=join(workspace,'demo-report.html');writeFileSync(html,'<!doctype html><meta charset="utf-8"><style>body{background:#17231e;color:#e5eee7;font:22px sans-serif;padding:38px}h1{font-size:32px}li{margin:20px 0}small{color:#a3b9a9}</style><h1>调试记录 · Demo</h1><small>本地 HTML / 示例数据</small><ul><li>USB 初始化：通过</li><li>传输超时：待分析</li><li>串口与 GDB 输出：已整理</li></ul><p>终端、Codex 与文档放在同一工作页。</p>');
 await page.evaluate(async html=>{__test.web=await __test.layout.openBrowser(__test.right,html);},html);
 await delay(4500);
 await chapter('终端日志为模拟数据；Codex 为真实 CLI，演示未向模型提交请求');await delay(3500);
 recording=false;await loop;
 const end=Date.now()-start;
 writeFileSync(join(dir,'frames.txt'),frames.map((f,i)=>`file '${f.file}'\nduration ${((frames[i+1]?.time??(start+end))-f.time)/1000}`).join('\n')+`\nfile '${frames.at(-1).file}'\n`);
 writeFileSync(join(dir,'captions.srt'),chapters.map((c,i)=>`${i+1}\n${stamp(c.time)} --> ${stamp(chapters[i+1]?.time??end)}\n${c.text}\n`).join('\n'));
 writeFileSync(join(dir,'recording.json'),JSON.stringify({duration:end,frames:frames.length,chapters},null,2));
 console.log('ARTIFACTS',dir);
} finally {recording=false;if(loop)await loop.catch(()=>{});if(instance)await instance.close();}
